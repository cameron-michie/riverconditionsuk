#!/bin/zsh
# Regenerate supabase/seed.sql from a database: the ref schema (the rulebook) and the ETL job definitions, as idempotent inserts.
#   scripts/migrate/dump_seed.sh [database name, default postgres]
# Uses pg_dump inside the local Supabase db container so the client matches the server version.
set -euo pipefail
DB=${1:-postgres}
OUT=${0:A:h}/../../supabase/seed.sql
C=supabase_db_riverconditionsuk
{
  echo "-- The rulebook as data: sources (with licences), organisations, units, parameters and their upstream aliases, small vocabularies,"
  echo "-- signals, bands and map layers; then the ETL job definitions. Generated by scripts/migrate/dump_seed.sh; edit the database, then regenerate."
  docker exec $C pg_dump -U postgres -d $DB --data-only --inserts --rows-per-insert=200 --on-conflict-do-nothing --no-comments -n ref \
    | grep -vE '^(SET|SELECT pg_catalog|--|$)' | grep -v '^\\'      # pg_dump's psql-only \restrict lines; the seed is loaded without psql
  echo
  docker exec $C psql -U postgres -d $DB -Atc "select 'insert into ops.etl_job (name, command, interval_minutes, enabled, timeout_s, max_lag_minutes, source_slug) values ' ||
      string_agg(format('(%L, %L, %s, %L, %s, %s, %L)', name, command, interval_minutes, enabled, timeout_s, coalesce(max_lag_minutes::text, 'null'), source_slug), E',\n  ' order by name) ||
      E'\non conflict (name) do nothing;' from ops.etl_job"
  docker exec $C psql -U postgres -d $DB -Atc "select format('select setval(pg_get_serial_sequence(%L, %L), %s);', 'ref.' || table_name, column_name, 'greatest(1, (select max(' || column_name || ') from ref.' || table_name || '))')
      from information_schema.columns where table_schema = 'ref' and is_identity = 'YES' order by table_name"
} > $OUT
wc -l $OUT
