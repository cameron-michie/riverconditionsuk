-- geo: geometry and places. Built by the loaders in scripts/load; ETL jobs add sites they discover.

-- A named river (derived from OS Open Rivers links). aliases: other names; research: placed literature, newest first.
create table geo.river (
  id              bigint generated by default as identity primary key,
  slug            text not null unique,
  name            text not null,
  name_cy         text,
  parent_river_id bigint references geo.river (id),
  mouth_node_id   bigint,
  source_node_id  bigint,
  length_km       double precision,
  strahler_max    smallint,
  river_class     smallint,
  aliases         text[] not null default '{}',
  research        jsonb not null default '[]',
  geom            public.geometry(MultiLineString, 4326),
  label_pt        public.geometry(Point, 4326)
);
create index river_geom_idx on geo.river using gist (geom);
create index river_label_pt_idx on geo.river using gist (label_pt) where label_pt is not null;
create index river_name_idx on geo.river using gin (name public.gin_trgm_ops);
create index river_parent_river_id_idx on geo.river (parent_river_id);
create index river_river_class_idx on geo.river (river_class);

-- A WFD waterbody ("stretch"). Classification, reasons for not achieving good and source apportionment are folded in as the
-- latest assessment only: classes = {element: {status, year, cycle, certainty, prev}}, reasons = [{sector, sector_native, activity, element, certainty}],
-- apportionment = [{pollutant, sector, share_pct, load_t_yr}]. radar_cells: 1 km radar cells inside the catchment, encoded ix * 10000 + iy.
create table geo.waterbody (
  id              bigint generated by default as identity primary key,
  wb_code         text not null unique,
  name            text,
  category        text,
  designation     text,
  country         text,
  river_id        bigint references geo.river (id),
  rbd             text,
  management_catchment  text,
  operational_catchment text,
  area_km2        double precision,
  length_km       double precision,
  source_id       bigint references ref.source (id),
  ids             jsonb not null default '{}',
  classes         jsonb not null default '{}',
  reasons         jsonb not null default '[]',
  apportionment   jsonb not null default '[]',
  radar_cells     integer[],
  catchment_geom  public.geometry(MultiPolygon, 4326),
  line_geom       public.geometry(MultiLineString, 4326)
);
create index waterbody_catchment_geom_idx on geo.waterbody using gist (catchment_geom);
create index waterbody_line_geom_idx on geo.waterbody using gist (line_geom);
create index waterbody_river_id_idx on geo.waterbody (river_id);

-- OS Open Rivers watercourse links: the drawn network and the routing graph.
create table geo.river_link (
  id              bigint generated by default as identity primary key,
  os_id           text not null unique,
  river_id        bigint references geo.river (id),
  waterbody_id    bigint references geo.waterbody (id),
  form            text,
  name            text,
  length_m        real,
  start_node_id   bigint,
  end_node_id     bigint,
  flow_direction  text,
  strahler        smallint,
  dist_to_mouth_m double precision,
  upstream_km     real,
  size_class      smallint,
  river_class     smallint,
  geom            public.geometry(LineString, 4326),
  geom_bng        public.geometry(LineString, 27700)
);
create index river_link_geom_idx on geo.river_link using gist (geom);
create index river_link_geom_bng_idx on geo.river_link using gist (geom_bng);
create index river_link_river_id_idx on geo.river_link (river_id);
create index river_link_waterbody_id_idx on geo.river_link (waterbody_id);
create index river_link_start_node_id_idx on geo.river_link (start_node_id);
create index river_link_end_node_id_idx on geo.river_link (end_node_id);
-- one spatial index per drawn stream class, so a zoomed-out network tile only scans the big rivers
create index river_link_c2 on geo.river_link using gist (geom) where river_class >= 2;
create index river_link_c4 on geo.river_link using gist (geom) where river_class >= 4;
create index river_link_c6 on geo.river_link using gist (geom) where river_class >= 6;
create index river_link_c7 on geo.river_link using gist (geom) where river_class >= 7;
create index river_link_c8 on geo.river_link using gist (geom) where river_class >= 8;
create index river_link_c9 on geo.river_link using gist (geom) where river_class >= 9;
create index river_link_c10 on geo.river_link using gist (geom) where river_class >= 10;
create index river_link_c11 on geo.river_link using gist (geom) where river_class >= 11;

-- Every polygon the map draws or the dossiers test against.
--   kind: country, national_park, urban_area, city, flood_outlook_area (FFC county areas), warning_area (EA flood warning/alert areas; geom only while active),
--         water (lakes, reservoirs, ponds; attrs.kind, attrs.river_id), beach (attrs.bathing_site_id), bridge (attrs.length_m), flood_zone (EA zones 2/3 near an active risk),
--         nutrient_neutrality (Natural England catchments; an input to the agricultural pressure signal)
create table geo.area (
  id        bigint generated by default as identity primary key,
  kind      text not null,
  code      text,
  name      text,
  name_alt  text,
  rank      smallint,
  area_km2  double precision,
  source_id bigint references ref.source (id),
  attrs     jsonb not null default '{}',
  geom      public.geometry(MultiPolygon, 4326),
  geom_lo   public.geometry(MultiPolygon, 4326),
  geom_mid  public.geometry(MultiPolygon, 4326),
  label_pt  public.geometry(Point, 4326),
  unique (kind, code)
);
create index area_geom_idx on geo.area using gist (geom);
create index area_geom_lo_idx on geo.area using gist (geom_lo);
create index area_label_pt_idx on geo.area using gist (label_pt);
create index area_kind_rank_idx on geo.area (kind, rank);

-- Every measuring, discharging or survey point, plus bridges.
--   kind: river_gauge, rain_gauge, groundwater_station, weather_station, wq_sampling_point, bathing_water, storm_overflow, sewage_works, survey_site, bridge
-- attrs carries the per-kind static facts that used to sit in side tables:
--   storm_overflow: permit_ref, receiving, asset_type, edm_installed_on, spills, spill_hours, spill_year, spills_prev, edm_operating_pct
--   sewage_works:   works (permit | monitoring point), permit_ref, permit_type, wq_type, monitor_site_id, measured
--   bathing_water:  water_type, class, class_year, class_prev
--   river_gauge:    stage scale (datum, typical_low, typical_high, highest_recent, highest_recent_at, max_on_record, max_on_record_at, min_on_record),
--                   NRFA descriptors (catchment_area, qmed, gdf_q95_flow, ...)
create table geo.site (
  id                bigint generated by default as identity primary key,
  kind              text not null,
  name              text,
  country           text,
  operator_id       bigint references ref.organisation (id),
  status            text,
  river_link_id     bigint references geo.river_link (id),
  river_id          bigint references geo.river (id),
  waterbody_id      bigint references geo.waterbody (id),
  snap_distance_m   real,
  dist_to_mouth_m   double precision,
  river_name_raw    text,
  primary_source_id bigint references ref.source (id),
  attrs             jsonb not null default '{}',
  geom              public.geometry(Point, 4326),
  geom_bng          public.geometry(Point, 27700)
);
create index site_geom_idx on geo.site using gist (geom);
create index site_geom_bng_idx on geo.site using gist (geom_bng);
create index site_kind_idx on geo.site (kind);
create index site_river_id_idx on geo.site (river_id);
create index site_waterbody_id_idx on geo.site (waterbody_id);
create index site_river_link_id_idx on geo.site (river_link_id);
create index site_operator_id_idx on geo.site (operator_id);

-- External identifiers -> site. A site can carry several values in one scheme.
create table geo.site_key (
  scheme  text not null,
  value   text not null,
  site_id bigint not null references geo.site (id) on delete cascade,
  primary key (scheme, value)
);
create index site_key_site_id_idx on geo.site_key (site_id);

-- Per gauge: the seasonal flow climatology and the fitted rain -> flow model. Rebuilt rarely, from the archive (scripts/etl/flow_normal_refresh.py)
-- and by scripts/etl/flow_model_fit.py. normal[k][i]: 37 ten-day steps (doy 1, 11, .. 361) x 21 quantiles (0, 5, .. 100 %), null where too little history.
create table geo.gauge_model (
  site_id         bigint primary key references geo.site (id) on delete cascade,
  normal          double precision[],
  normal_years    integer,
  beta            double precision[],
  sd              double precision,
  r2              double precision,
  trained_through date,
  built_at        timestamptz not null default now()
);

-- the river that drains most of each waterbody
create function geo.refresh_waterbody_river()
returns void
language sql
set search_path = ''
as $$
  update geo.waterbody w set river_id = x.river_id
  from (select distinct on (waterbody_id) waterbody_id, river_id from (
          select waterbody_id, river_id, sum(length_m) len from geo.river_link
          where waterbody_id is not null and river_id is not null group by 1, 2) q
        order by waterbody_id, len desc) x
  where x.waterbody_id = w.id and w.river_id is distinct from x.river_id;
$$;
