-- ref: vocabularies, sources and rules. Small, seeded (supabase/seed.sql), rarely change.

-- Every upstream dataset, with its licence folded in.
create table ref.source (
  id                    bigint generated by default as identity primary key,
  slug                  text not null unique,
  name                  text not null,
  publisher             text,
  country               text,
  kind                  text,
  base_url              text,
  evidence_class        text,
  cadence               text,
  status                text not null default 'active',
  datasets              text[],
  licence               text,
  licence_name          text,
  licence_url           text,
  attribution           text,
  allows_redistribution boolean,
  allows_commercial     boolean
);

create table ref.organisation (
  id      bigint generated by default as identity primary key,
  slug    text not null unique,
  name    text not null,
  kind    text,
  country text,
  aliases text[] not null default '{}'
);
create index organisation_aliases_idx on ref.organisation using gin (aliases);

create table ref.unit (
  id           text primary key,
  label        text,
  symbol       text,
  dimension    text,
  is_canonical boolean not null default false,
  factor       numeric,
  "offset"     numeric not null default 0,
  aliases      text[] not null default '{}'
);
create unique index unit_one_canonical on ref.unit (dimension) where is_canonical;

create table ref.parameter (
  id             bigint generated by default as identity primary key,
  code           text not null unique,
  name           text not null,
  domain         text,
  canonical_unit text references ref.unit (id),
  description    text,
  signal_code    text,
  higher_is      text,
  plausible_min  double precision,
  plausible_max  double precision
);
create index parameter_canonical_unit_idx on ref.parameter (canonical_unit);

-- (source, native determinand) -> parameter and unit: how loaders map upstream codes.
create table ref.parameter_alias (
  id           bigint generated by default as identity primary key,
  source_id    bigint references ref.source (id),
  native_code  text not null,
  native_label text,
  native_unit  text,
  parameter_id bigint references ref.parameter (id),
  unit_id      text references ref.unit (id),
  fraction     text,
  method       text,
  matrix       text,
  status       text not null default 'mapped',
  confidence   real,
  unique (source_id, native_code)
);
create index parameter_alias_parameter_id_idx on ref.parameter_alias (parameter_id);

-- Small labelled vocabularies, one row per code. native holds the upstream spellings that map to the code.
--   domain: country, evidence_class, wfd_element, wfd_status, pressure_sector, bathing_class, overflow_status, obs_quality
create table ref.term (
  domain text not null,
  code   text not null,
  label  text,
  about  text,
  sort   smallint,
  native text[] not null default '{}',
  attrs  jsonb not null default '{}',
  primary key (domain, code)
);
create index term_native_idx on ref.term using gin (native);

-- The health and flow signals shown per stretch and river.
create table ref.signal (
  code        text primary key,
  label       text not null,
  short_label text,
  description text,
  words       text[],
  sort        smallint not null,
  is_pressure boolean not null default false
);

-- Banding rules. kind: level and flow (flood index, from_value = index), flow_pct (seasonal percentile, from_value = percentile).
create table ref.band (
  kind       text not null,
  from_value numeric not null,
  band       text not null,
  rank       smallint not null,
  label      text,
  about      text,
  primary key (kind, from_value)
);

-- Map layers. zoom_rules: [[from_zoom, threshold], ...], the minimum size (stream class, length or area) drawn from that zoom up.
create table ref.map_layer (
  code           text primary key,
  label          text not null,
  grp            text not null,
  geom_kind      text not null,
  min_zoom       smallint not null default 0,
  cluster_below  smallint,
  hot_only_below smallint,
  default_on     boolean not null default false,
  has_labels     boolean not null default false,
  labels_default boolean not null default false,
  sort           smallint not null default 0,
  max_features   integer not null default 4000,
  zoom_rules     jsonb not null default '[]'
);

-- threshold for a layer at a zoom, from its zoom_rules
create function ref.zoom_threshold(p_layer text, p_zoom integer)
returns numeric
language sql
stable
set search_path = ''
as $$
  select coalesce((select (r ->> 1)::numeric from ref.map_layer l, jsonb_array_elements(l.zoom_rules) r
                   where l.code = p_layer and (r ->> 0)::int <= p_zoom order by (r ->> 0)::int desc limit 1), 0);
$$;
