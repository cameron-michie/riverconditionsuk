-- ops: the ETL scheduler, its run log and the cold-archive ledger.
-- pg_cron runs ops.dispatch_job(name) per job (entries made by ops.sync_cron() from ops.etl_job); dispatch POSTs to the ETL Compute app
-- (URL and token in Vault). Locally, scripts/etl/scheduler.py does the same from launchd.

create table ops.etl_job (
  name             text primary key,
  command          text not null,
  interval_minutes integer not null,
  enabled          boolean not null default true,
  timeout_s        integer not null default 1800,
  max_lag_minutes  integer,
  source_slug      text,
  running_since    timestamptz,
  last_started_at  timestamptz,
  last_finished_at timestamptz,
  last_status      text
);

-- One row per job run (scheduler or manual). Scripts add the source and rows written to the scheduler's row (ETL_RUN_ID). Kept 14 days.
create table ops.etl_run (
  id           bigint generated by default as identity primary key,
  job          text not null,
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  status       text not null default 'running',
  output       text,
  request_id   bigint,
  source_id    bigint references ref.source (id),
  rows_written bigint,
  error        text
);
create index etl_run_job_started_at_idx on ops.etl_run (job, started_at desc);

-- Parquet files in the Storage bucket `archive`: readings that aged out of live.observation. Written by scripts/etl/archive.py,
-- read back only by rare rebuilds (scripts/etl/flow_normal_refresh.py).
create table ops.archive_object (
  id           bigint generated by default as identity primary key,
  dataset      text not null,
  period_start timestamptz not null,
  period_end   timestamptz not null,
  bucket       text not null default 'archive',
  path         text not null,
  rows         bigint not null,
  bytes        bigint,
  sha256       text,
  archived_at  timestamptz not null default now(),
  dropped_at   timestamptz,
  unique (bucket, path)
);

create view ops.job_freshness with (security_invoker = true) as
  select name, source_slug, enabled, interval_minutes, max_lag_minutes, last_status, last_started_at, last_finished_at,
         round(extract(epoch from now() - last_finished_at) / 60) minutes_since_finish,
         coalesce(last_status in ('failed', 'timeout'), false) failing,
         enabled and (last_finished_at is null or extract(epoch from now() - last_finished_at) / 60 > coalesce(max_lag_minutes, interval_minutes * 3)) stale
  from ops.etl_job;

-- a cron expression for "every n minutes", offset per job so they do not all start on the same minute
create function ops.cron_expr(p_name text, p_minutes integer)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_minutes < 60 then (select string_agg(m::text, ',' order by m) from generate_series(abs(hashtext(p_name)) % p_minutes, 59, p_minutes) m) || ' * * * *'
    when p_minutes < 1440 and p_minutes % 60 = 0 then (abs(hashtext(p_name)) % 60)::text || ' */' || (p_minutes / 60) || ' * * *'
    when p_minutes = 1440 then (abs(hashtext(p_name)) % 60)::text || ' ' || (2 + abs(hashtext(p_name)) % 3)::text || ' * * *'
    when p_minutes = 10080 then (abs(hashtext(p_name)) % 60)::text || ' 3 * * 0'
    when p_minutes >= 129600 then (abs(hashtext(p_name)) % 60)::text || ' 4 1 */3 *'
    else (abs(hashtext(p_name)) % 60)::text || ' 4 1 * *' end
$$;

-- start one job on the ETL container
create function ops.dispatch_job(p_name text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare j ops.etl_job%rowtype; rid bigint; base text; tok text; req bigint;
begin
  select * into j from ops.etl_job where name = p_name and enabled;
  if not found then return null; end if;
  if j.running_since is not null and j.running_since > now() - make_interval(secs => greatest(j.timeout_s, 600) + 600) then return null; end if;   -- still running
  select decrypted_secret into base from vault.decrypted_secrets where name = 'etl_url';
  select decrypted_secret into tok from vault.decrypted_secrets where name = 'etl_token';
  update ops.etl_job set running_since = now(), last_started_at = now() where name = p_name;
  insert into ops.etl_run (job) values (p_name) returning id into rid;
  select net.http_post(url := base || '/run', headers := jsonb_build_object('Content-Type', 'application/json', 'X-ETL-Token', tok),
                       body := jsonb_build_object('job', p_name, 'run_id', rid), timeout_milliseconds := 20000) into req;
  update ops.etl_run set request_id = req where id = rid;
  return rid;
end $$;

-- fail runs whose dispatch errored or that never reported back
create function ops.check_dispatches()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare n int;
begin
  with bad as (
    select r.id, r.job, coalesce(h.status_code::text, 'no response') || ' ' || left(coalesce(h.content, h.error_msg, ''), 200) as why
    from ops.etl_run r left join net._http_response h on h.id = r.request_id
    where r.finished_at is null and r.request_id is not null and r.started_at > now() - interval '1 day'
      and ((h.id is not null and (h.status_code is null or h.status_code not between 200 and 299)) or (h.id is null and r.started_at < now() - interval '3 minutes'))),
  u as (update ops.etl_run r set finished_at = now(), status = 'failed', output = 'dispatch failed: ' || bad.why from bad where r.id = bad.id returning r.job)
  update ops.etl_job j set running_since = null, last_finished_at = now(), last_status = 'failed' where j.name in (select job from u);
  get diagnostics n = row_count;
  -- a run whose container was replaced mid-job (a redeploy) never reports back: close it once it has outlived its timeout
  with dead as (
    update ops.etl_run r set finished_at = now(), status = 'timeout', output = coalesce(output, '') || 'no result recorded: container restarted or job outlived its timeout'
    from ops.etl_job j where j.name = r.job and r.request_id is not null and r.finished_at is null and r.started_at < now() - make_interval(secs => j.timeout_s + 300) returning r.job)
  update ops.etl_job j set running_since = null, last_finished_at = now(), last_status = 'timeout' where j.name in (select job from dead);
  return n;
end $$;

-- daily housekeeping: the run log keeps 14 days; live.trim() covers rain, warnings and surveys
create function ops.housekeep()
returns void
language sql
set search_path = ''
as $$
  delete from ops.etl_run where started_at < now() - interval '14 days';
  select live.trim();
$$;

-- make pg_cron match ops.etl_job: one entry per enabled job, plus the dispatch check and daily housekeeping
create function ops.sync_cron()
returns table (jobname text, schedule text)
language plpgsql
security definer
set search_path = ''
as $$
declare j record;
begin
  for j in select name, interval_minutes from ops.etl_job where enabled loop
    perform cron.schedule('etl:' || j.name, ops.cron_expr(j.name, j.interval_minutes), format('select ops.dispatch_job(%L)', j.name));
  end loop;
  perform cron.schedule('etl:_check', '*/2 * * * *', 'select ops.check_dispatches()');
  perform cron.schedule('etl:_housekeep', '5 1 * * *', 'select ops.housekeep()');
  perform cron.unschedule(c.jobname) from cron.job c where c.jobname like 'etl:%' and c.jobname not in ('etl:_check', 'etl:_housekeep')
    and substring(c.jobname from 5) not in (select name from ops.etl_job where enabled);
  return query select c.jobname::text, c.schedule::text from cron.job c where c.jobname like 'etl:%' order by 1;
end $$;
