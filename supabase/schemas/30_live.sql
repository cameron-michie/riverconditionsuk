-- live: what the scheduled ETL jobs keep current. No history: readings are kept 7 days (sparse series: their last 12 values), then
-- scripts/etl/archive.py moves them to Parquet in Storage (the cold archive, ledger in ops.archive_object) and deletes them here.

-- One measured series: site x parameter x source. latest_* is the newest reading, kept on the row.
create table live.series (
  id                bigint generated by default as identity primary key,
  site_id           bigint not null references geo.site (id) on delete cascade,
  parameter_id      bigint not null references ref.parameter (id),
  source_id         bigint not null references ref.source (id),
  source_series_key text not null,
  aggregation       text,
  interval_s        integer,
  unit_id           text references ref.unit (id),
  native_unit       text,
  qualifier         text,
  datum             text,
  matrix            text,
  fraction          text,
  method            text,
  evidence_class    text,
  status            text not null default 'active',
  first_at          timestamptz,
  last_at           timestamptz,
  attrs             jsonb not null default '{}',
  latest_at         timestamptz,
  latest_value      double precision,
  latest_censor     text,
  latest_quality    text,
  unique (source_id, source_series_key)
);
create index series_site_id_parameter_id_idx on live.series (site_id, parameter_id);
create index series_parameter_id_idx on live.series (parameter_id);

-- Readings. No foreign key to series by design: bulk loads stay fast and a retired series' readings age out on their own.
create table live.observation (
  series_id   bigint not null,
  observed_at timestamptz not null,
  value       double precision,
  censor      text,
  quality     text not null default 'unchecked',
  primary key (series_id, observed_at)
);
create index observation_observed_brin on live.observation using brin (observed_at);

-- Current state per site. kind: gauge (state = band, rank = band rank), overflow (state = EDM status), works (latest effluent readings in detail).
create table live.site_now (
  site_id    bigint primary key references geo.site (id) on delete cascade,
  kind       text not null,
  state      text,
  rank       smallint,
  at         timestamptz,
  since      timestamptz,
  stage      double precision,
  flow       double precision,
  flow_pct   real,
  detail     jsonb not null default '{}',
  updated_at timestamptz not null default now()
);
create index site_now_kind_idx on live.site_now (kind, rank);

-- Health and flow signals per waterbody and river.
create table live.signal (
  entity_kind    text not null,
  entity_id      bigint not null,
  signal_code    text not null references ref.signal (code),
  state          text,
  state_rank     smallint,
  trend          text,
  basis          jsonb,
  evidence_class text,
  as_of          timestamptz,
  summary        text,
  primary key (entity_kind, entity_id, signal_code)
);
create index signal_signal_code_state_rank_idx on live.signal (signal_code, state_rank);

-- Per waterbody: the compact signal strings the network tiles carry (s = ranks, t = trends, one character per signal in ref.signal sort order),
-- and the latest modelled flow, now and the next days (flow_days: [{at, pct, q, method, confidence, sd_z, q_factor}]).
create table live.waterbody_now (
  waterbody_id   bigint primary key references geo.waterbody (id) on delete cascade,
  s              text,
  t              text,
  flow_issued_at timestamptz,
  flow_area_km2  double precision,
  flow_days      jsonb
);

-- Catchment rain per waterbody: radar (the last 8 days, 15-minute steps) and the latest ECMWF IFS run. Parallel arrays: at[i] is the end of step i.
create table live.rain (
  waterbody_id bigint not null references geo.waterbody (id) on delete cascade,
  source       text not null,
  issued_at    timestamptz,
  step_min     smallint not null,
  at           timestamptz[] not null default '{}',
  mm           real[] not null default '{}',
  primary key (waterbody_id, source)
);

-- Weather map frames: rain images in Storage (path, bbox, legend) and pressure isobars (lines: [{l: hPa, g: coordinates}]).
create table live.weather (
  id        bigint generated by default as identity primary key,
  product   text not null,
  issued_at timestamptz not null,
  valid_at  timestamptz not null,
  path      text,
  bbox      double precision[],
  legend    jsonb,
  lines     jsonb,
  unique (product, issued_at, valid_at)
);

-- Flood information now. kind: outlook (Flood Forecasting Centre 5-day risk per county area, latest statement only),
-- warning (EA flood warnings and alerts in force; severity 1 severe .. 4 no longer in force).
create table live.flood (
  id            bigint generated by default as identity primary key,
  kind          text not null,
  area_id       bigint not null references geo.area (id) on delete cascade,
  issued_at     timestamptz,
  statement_id  text,
  day           smallint,
  forecast_date date,
  risk          text,
  severity      smallint,
  message       text,
  changed_at    timestamptz,
  attrs         jsonb not null default '{}'
);
create unique index flood_outlook_uq on live.flood (area_id, day) where kind = 'outlook';
create unique index flood_warning_uq on live.flood (area_id) where kind = 'warning';

-- Citizen-science surveys from the last 36 months (Big River Watch, Riverfly, weekly volunteer visits).
create table live.survey (
  id             bigint generated by default as identity primary key,
  source_id      bigint not null references ref.source (id),
  source_key     text not null,
  kind           text not null,
  site_id        bigint references geo.site (id) on delete set null,
  waterbody_id   bigint references geo.waterbody (id),
  river_id       bigint references geo.river (id),
  surveyed_at    timestamptz,
  summary_label  text,
  summary_score  numeric,
  breach         boolean,
  answers        jsonb not null default '{}',
  evidence_class text not null default 'citizen_science',
  unique (source_id, source_key)
);
create index survey_waterbody_id_idx on live.survey (waterbody_id, kind, surveyed_at desc);
create index survey_site_id_idx on live.survey (site_id, kind, surveyed_at desc);

-- ─── helpers ───

create function live.norm_cdf(z double precision)
returns double precision
language plpgsql
immutable
set search_path = ''
as $$
declare t double precision := 1 / (1 + 0.2316419 * abs(z)); d double precision := 0.3989423 * exp(-z * z / 2); pr double precision;
begin
  pr := d * t * (0.319381530 + t * (-0.356563782 + t * (1.781477937 + t * (-1.821255978 + t * 1.330274429))));
  return case when z > 0 then 1 - pr else pr end;
end $$;

create function live.norm_inv(p double precision)
returns double precision
language plpgsql
immutable
set search_path = ''
as $$
declare q double precision; t double precision;   -- Abramowitz and Stegun 26.2.23
begin
  p := least(0.999, greatest(0.001, p));
  q := case when p < 0.5 then p else 1 - p end; t := sqrt(-2 * ln(q));
  t := t - (2.515517 + 0.802853 * t + 0.010328 * t * t) / (1 + 1.432788 * t + 0.189269 * t * t + 0.001308 * t * t * t);
  return case when p < 0.5 then -t else t end;
end $$;

create function live.ordinal(n integer)
returns text
language sql
immutable
set search_path = ''
as $$
  select n::text || case when n % 100 between 11 and 13 then 'th' else case n % 10 when 1 then 'st' when 2 then 'nd' when 3 then 'rd' else 'th' end end;
$$;

-- percentile of a flow against the gauge's seasonal climatology (geo.gauge_model.normal)
create function live.seasonal_pct(p_site bigint, p_flow double precision, p_at timestamptz default now())
returns real
language plpgsql
stable
set search_path = ''
as $$
declare qs double precision[]; i int; lo double precision; hi double precision; d int := extract(doy from p_at)::int; k int;
begin
  k := 1 + round((d - 1) / 10.0)::int; if k > 37 then k := 37; end if;
  select array(select unnest(m.normal[k:k][1:21])) into qs from geo.gauge_model m where m.site_id = p_site;
  if qs is null or cardinality(qs) < 21 or qs[1] is null then return null; end if;
  if p_flow <= qs[1] then return 0; end if; if p_flow >= qs[21] then return 100; end if;
  for i in 1..20 loop
    if p_flow <= qs[i + 1] then lo := qs[i]; hi := qs[i + 1]; return ((i - 1) * 5 + case when hi > lo then 5 * (p_flow - lo) / (hi - lo) else 2.5 end)::real; end if;
  end loop;
  return null;
end $$;

