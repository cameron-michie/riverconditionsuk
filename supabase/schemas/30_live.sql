-- gauges: latest stage and flow against the stage scale, QMED and the seasonal normal
create function live.refresh_gauges()
returns void
language plpgsql
set search_path = ''
as $$
begin
  delete from live.site_now where kind = 'gauge';
  insert into live.site_now (site_id, kind, state, rank, at, stage, flow, flow_pct, detail)
  with lv as (
    select distinct on (s.site_id) s.site_id, s.latest_value value, s.latest_at observed_at
    from live.series s join ref.parameter p on p.id = s.parameter_id and p.code = 'water_level'
    where s.source_id = (select id from ref.source where slug = 'ea_flood_monitoring') and s.latest_value is not null and s.latest_at > now() - interval '10 days'
    order by s.site_id, (s.qualifier ilike 'stage') desc, (s.datum = 'mASD') desc, s.latest_at desc),
  fl as (
    select distinct on (s.site_id) s.site_id, s.latest_value value, s.latest_at observed_at
    from live.series s join ref.parameter p on p.id = s.parameter_id and p.code = 'river_flow'
    where s.source_id in (select id from ref.source where slug in ('ea_flood_monitoring', 'ea_hydrology', 'sepa_kiwis')) and s.latest_value is not null and s.latest_at > now() - interval '10 days'
    order by s.site_id, s.latest_at desc),
  base as (
    select coalesce(lv.site_id, fl.site_id) site_id, lv.observed_at stage_at, fl.value flow, fl.observed_at flow_at, a.*,
           -- the stage scale is in stage units; some series are in metres above Ordnance Datum. Take whichever reading sits inside the station's envelope.
           case when a.max_on_record is null or lv.value is null then null
                when lv.value between a.min_on_record - 0.5 and a.max_on_record + 1.0 then lv.value
                when a.datum is not null and lv.value - a.datum between a.min_on_record - 0.5 and a.max_on_record + 1.0 then lv.value - a.datum end stage
    from lv full join fl on fl.site_id = lv.site_id
    join geo.site st on st.id = coalesce(lv.site_id, fl.site_id)
    cross join lateral (select (st.attrs->>'datum')::float8 datum, (st.attrs->>'typical_low')::float8 typical_low, (st.attrs->>'typical_high')::float8 typical_high,
                               (st.attrs->>'max_on_record')::float8 max_on_record, (st.attrs->>'min_on_record')::float8 min_on_record, (st.attrs->>'highest_recent')::float8 highest_recent,
                               (st.attrs->>'qmed')::float8 qmed, (st.attrs->>'gdf_q95_flow')::float8 q95, (st.attrs->>'gdf_q50_flow')::float8 q50,
                               (st.attrs->>'gdf_q10_flow')::float8 q10, (st.attrs->>'gdf_q05_flow')::float8 q05) a),
  calc as (
    select b.*, case when b.stage is not null and b.max_on_record > b.typical_high then (b.stage - b.typical_high) / (b.max_on_record - b.typical_high) end lidx,
           case when b.flow is not null and b.qmed > 0 then b.flow / b.qmed end fidx,
           case when b.flow is null then null
                when b.q95 is not null and b.q50 is not null and b.q10 is not null and b.q05 is not null then
                  case when b.flow <= b.q95 then 5 * b.flow / nullif(b.q95, 0) when b.flow <= b.q50 then 5 + 45 * (b.flow - b.q95) / nullif(b.q50 - b.q95, 0)
                       when b.flow <= b.q10 then 50 + 40 * (b.flow - b.q50) / nullif(b.q10 - b.q50, 0) when b.flow <= b.q05 then 90 + 5 * (b.flow - b.q10) / nullif(b.q05 - b.q10, 0) else 95 + least(5, 5 * (b.flow - b.q05) / nullif(b.q05, 0)) end end fpct
    from base b),
  banded as (
    select c.*, case when c.stage is null then null when c.stage < c.typical_low then 'low' else (select r.band from ref.band r where r.kind = 'level' and r.from_value <= coalesce(c.lidx, -1000) order by r.from_value desc limit 1) end lband,
           case when c.flow is null then null when c.q95 is not null and c.flow <= c.q95 then 'low' when c.fidx is null then null else (select r.band from ref.band r where r.kind = 'flow' and r.from_value <= c.fidx order by r.from_value desc limit 1) end fband
    from calc c),
  ranked as (
    select b.*, greatest(coalesce(array_position(array['low','normal','elevated','high','severe'], lband), 0), coalesce(array_position(array['low','normal','elevated','high','severe'], fband), 0)) rk
    from banded b)
  select site_id, 'gauge', (array['low','normal','elevated','high','severe'])[rk], rk, greatest(stage_at, flow_at), stage, flow,
         coalesce(live.seasonal_pct(site_id, flow, flow_at), fpct),
         jsonb_strip_nulls(jsonb_build_object('stage_at', stage_at, 'flow_at', flow_at, 'typical_low', typical_low, 'typical_high', typical_high, 'max_on_record', max_on_record,
                                              'highest_recent', highest_recent, 'level_index', lidx, 'level_band', lband, 'qmed', qmed, 'flow_q95', q95, 'flow_index', fidx, 'flow_band', fband))
  from ranked where rk > 0;
end $$;

-- sewage works: latest effluent readings from each works' monitoring point, kept on the row so tiles stay cheap
create function live.refresh_works()
returns void
language plpgsql
set search_path = ''
as $$
begin
  delete from live.site_now where kind = 'works';
  insert into live.site_now (site_id, kind, at, detail)
  select w.id, 'works', x.at, jsonb_build_object('latest', x.latest)
  from geo.site w
  join (select s.site_id, jsonb_object_agg(p.code, jsonb_build_object('v', s.latest_value, 'c', s.latest_censor, 'u', u.symbol)) latest, max(s.latest_at) at
        from live.series s join ref.parameter p on p.id = s.parameter_id join ref.unit u on u.id = s.unit_id
        where s.matrix = 'effluent' and p.code in ('ammonia_total_n', 'bod5', 'suspended_solids', 'phosphorus_total') and (s.latest_value is not null or s.latest_censor is not null)
        group by s.site_id) x on x.site_id = coalesce((w.attrs->>'monitor_site_id')::bigint, w.id)
  where w.kind = 'sewage_works' and w.attrs ? 'works'
  on conflict (site_id) do update set at = excluded.at, detail = excluded.detail, updated_at = now();
end $$;

-- per waterbody: the compact rank and trend strings the network tiles carry
create function live.refresh_waterbody_state()
returns void
language sql
set search_path = ''
as $$
  insert into live.waterbody_now (waterbody_id, s, t)
  select w.id,
         (select string_agg(coalesce(sg.state_rank::text, '0'), '' order by d.sort) from ref.signal d left join live.signal sg on sg.entity_kind = 'waterbody' and sg.entity_id = w.id and sg.signal_code = d.code),
         (select string_agg(case sg.trend when 'improving' then '+' when 'worsening' then '-' else '0' end, '' order by d.sort) from ref.signal d left join live.signal sg on sg.entity_kind = 'waterbody' and sg.entity_id = w.id and sg.signal_code = d.code)
  from geo.waterbody w
  on conflict (waterbody_id) do update set s = excluded.s, t = excluded.t;
$$;

-- flow signal per waterbody (measured at a gauge on or near it, or estimated from nearby gauges) and per river (average of its stretches)
create function live.refresh_flow_signals()
returns void
language plpgsql
set search_path = ''
as $$
begin
  delete from live.signal where signal_code = 'flow';
  create temp table _wb on commit drop as
    select l.waterbody_id wid, (array_agg(l.river_id order by rl.len desc nulls last))[1] river_id, avg(l.dist_to_mouth_m) ch, round(avg(l.size_class))::int sz,
           public.ST_Centroid(public.ST_Collect(public.ST_LineInterpolatePoint(l.geom, 0.5))) pt
    from geo.river_link l left join (select waterbody_id wb, river_id rid, sum(length_m) len from geo.river_link group by 1, 2) rl on rl.wb = l.waterbody_id and rl.rid = l.river_id
    where l.waterbody_id is not null group by l.waterbody_id;
  alter table _wb add column rname text; update _wb w set rname = r.name from geo.river r where r.id = w.river_id;
  create temp table _g on commit drop as
    select s.id gid, s.name, s.river_id, r.name rname, s.waterbody_id, s.dist_to_mouth_m ch, g.flow, g.flow_pct, s.geom pt, coalesce(l.size_class, 0) sz, r.length_km rlen
    from live.site_now g join geo.site s on s.id = g.site_id left join geo.river_link l on l.id = s.river_link_id left join geo.river r on r.id = s.river_id
    where g.kind = 'gauge' and g.flow_pct is not null and (g.detail->>'flow_at')::timestamptz > now() - interval '10 days';
  -- measured
  create temp table _m on commit drop as
    select w.wid, g.gid, g.name gname, g.flow, g.flow_pct pct, g.waterbody_id = w.wid on_stretch, round((public.ST_Distance(g.pt::public.geography, w.pt::public.geography) / 1000)::numeric) km, g.ch > w.ch upstream
    from _wb w
    join lateral (select * from _g g where g.river_id is not null and (g.waterbody_id = w.wid
                    or (g.rname = w.rname and public.ST_Distance(g.pt::public.geography, w.pt::public.geography) <= case when g.rlen > 150 then 100000 else 50000 end))
                  order by (g.waterbody_id = w.wid) desc, public.ST_Distance(g.pt::public.geography, w.pt::public.geography) limit 1) g on true;
  -- estimated: weighted normal score of nearby gauges
  create temp table _e on commit drop as
    with cand as (
      select w.wid, g.gid, g.name, g.flow_pct, public.ST_Distance(w.pt::public.geography, g.pt::public.geography) / 1000 d, abs(g.sz - coalesce(w.sz, 0)) dsz
      from _wb w join _g g on public.ST_DWithin(w.pt::public.geography, g.pt::public.geography, 80000)
      where w.wid not in (select wid from _m)),
    ranked as (select *, row_number() over (partition by wid order by d + 4 * dsz) rn, 1 / power(d + 10, 2) * exp(-0.6 * dsz) w, live.norm_inv(least(99.5, greatest(0.5, flow_pct)) / 100) z from cand)
    select wid, count(*) n, min(d) near, sum(w * z) / sum(w) zbar, sqrt(greatest(0, sum(w * z * z) / sum(w) - power(sum(w * z) / sum(w), 2))) spread,
           jsonb_agg(jsonb_build_object('gauge', gid, 'name', name, 'km', round(d::numeric), 'pct', round(flow_pct::numeric)) order by rn) donors
    from ranked where rn <= 5 group by wid having (count(*) >= 2 and min(d) <= 60) or min(d) <= 20;
  insert into live.signal (entity_kind, entity_id, signal_code, state, state_rank, trend, basis, evidence_class, as_of, summary)
  select 'waterbody', m.wid, 'flow', r.band, r.rank, 'unknown',
         jsonb_build_object('method', 'measured', 'gauge', m.gid, 'gauge_name', m.gname, 'pct', round(m.pct::numeric), 'flow', round(m.flow::numeric, 3), 'on_stretch', m.on_stretch, 'km_along_river', m.km),
         'official_monitoring', now(),
         'Flow at ' || m.gname || case when m.on_stretch then '' else ' (' || m.km || ' km ' || case when m.upstream then 'upstream' else 'downstream' end || ' on the same river)' end
           || ' is ' || r.label || ': ' || live.ordinal(round(m.pct::numeric)::int) || ' percentile for the time of year.'
  from _m m join lateral (select * from ref.band r where r.kind = 'flow_pct' and r.from_value <= m.pct order by r.from_value desc limit 1) r on true;
  insert into live.signal (entity_kind, entity_id, signal_code, state, state_rank, trend, basis, evidence_class, as_of, summary)
  select 'waterbody', e.wid, 'flow', r.band, r.rank, 'unknown',
         jsonb_build_object('method', 'estimated', 'pct', round(p::numeric), 'donors', e.donors, 'n', e.n, 'nearest_km', round(e.near::numeric),
                            'confidence', case when e.n >= 3 and e.near <= 25 and e.spread < 0.8 then 'medium' else 'low' end),
         'modelled', now(),
         'Estimated from ' || e.n || ' nearby gauge' || case when e.n > 1 then 's' else '' end || ' (nearest ' || round(e.near::numeric) || ' km): ' || r.label || ', about the ' || live.ordinal(round(p::numeric)::int) || ' percentile for the time of year.'
  from (select e.*, 100 * live.norm_cdf(e.zbar) p from _e e) e
  join lateral (select * from ref.band r where r.kind = 'flow_pct' and r.from_value <= e.p order by r.from_value desc limit 1) r on true;
  -- rivers: average of their stretches
  insert into live.signal (entity_kind, entity_id, signal_code, state, state_rank, trend, basis, evidence_class, as_of, summary)
  select 'river', x.river_id, 'flow', r.band, r.rank, 'unknown', jsonb_build_object('stretches', x.n, 'measured', x.nm), case when x.nm > 0 then 'official_monitoring' else 'modelled' end, now(),
         'Average over ' || x.n || ' stretch' || case when x.n > 1 then 'es' else '' end || ' (' || x.nm || ' measured, ' || (x.n - x.nm) || ' estimated): ' || r.label || '.'
  from (select w.river_id, count(*) n, count(*) filter (where s.basis ->> 'method' = 'measured') nm, round(avg(s.state_rank))::int rk
        from live.signal s join _wb w on w.wid = s.entity_id where s.entity_kind = 'waterbody' and s.signal_code = 'flow' and w.river_id is not null group by w.river_id) x
  join ref.band r on r.kind = 'flow_pct' and r.rank = x.rk;
  perform live.refresh_waterbody_state();
end $$;

-- mark readings outside a parameter's plausible range as suspect
create function live.flag_implausible(p_since timestamptz default '-infinity')
returns bigint
language sql
set search_path = ''
as $$
  with f as (
    update live.observation o set quality = 'suspect'
    from live.series s join ref.parameter p on p.id = s.parameter_id
    where s.id = o.series_id and o.observed_at >= p_since and o.quality in ('unchecked','good','provisional') and o.value is not null
      and ((p.plausible_min is not null and o.value < p.plausible_min) or (p.plausible_max is not null and o.value > p.plausible_max))
    returning 1) select count(*) from f;
$$;

-- retire series whose unit cannot measure their parameter (an upstream mapping error)
create function live.retire_inconsistent_series()
returns bigint
language sql
set search_path = ''
as $$
  with r as (
    update live.series s set status = 'retired', attrs = s.attrs || jsonb_build_object('retired_reason', 'parameter/unit mismatch upstream')
    from ref.parameter p, ref.unit u
    where p.id = s.parameter_id and u.id = s.unit_id and s.status <> 'retired'
      and u.dimension <> (select u2.dimension from ref.unit u2 where u2.id = p.canonical_unit)
    returning 1) select count(*) from r;
$$;

-- daily housekeeping for what the archive job does not cover: radar rain older than 8 days, expired flood warnings, old surveys
create function live.trim()
returns void
language sql
set search_path = ''
as $$
  update live.rain r set at = x.at, mm = x.mm
  from (select r2.waterbody_id, r2.source, array_agg(u.t order by u.t) at, array_agg(u.v order by u.t) mm
        from live.rain r2 cross join lateral unnest(r2.at, r2.mm) u(t, v)
        where r2.source = 'radar' and u.t > now() - interval '8 days' group by 1, 2) x
  where r.waterbody_id = x.waterbody_id and r.source = x.source;
  delete from live.flood where kind = 'warning' and (severity >= 4 or changed_at < now() - interval '7 days');
  delete from live.survey where surveyed_at < now() - interval '36 months';
$$;
